  "Hello, my name is registered on connectx24. " +
  "I am here to verify my identity on this platform. " +
  "This is my real voice and I am recording it honestly. " +
  "I speak clearly and I am proud of my language. " +
  "I will respect the community rules and be kind to everyone. " +
  "Thank you, I look forward to your approval.";

export function getVoicePhrase(
  languageCode: string | null | undefined,
): string {
  if (!languageCode) return VOICE_PHRASE_FALLBACK;
  return VOICE_PHRASES[languageCode] ?? VOICE_PHRASE_FALLBACK;
}
